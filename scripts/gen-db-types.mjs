#!/usr/bin/env node
// Generates src/lib/database.types.ts (supabase-js `Database` shape) from a migrated database.
// Equivalent to `supabase gen types typescript`, without Docker.
// Usage: node scripts/gen-db-types.mjs <postgres-url>
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const url = process.argv[2];
if (!url) {
  console.error('Usage: node scripts/gen-db-types.mjs <postgres-url>');
  process.exit(1);
}

const query = String.raw`
with cols as (
  select c.table_name, c.column_name, c.ordinal_position, c.is_nullable = 'YES' as nullable,
         (c.column_default is not null or c.is_identity = 'YES' or c.is_generated = 'ALWAYS') as has_default,
         c.data_type, c.udt_schema, c.udt_name
  from information_schema.columns c
  join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
),
fks as (
  select con.conname, rel.relname as table_name, frel.relname as ref_table,
         array(select a.attname from unnest(con.conkey) with ordinality k(n, o)
               join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.n order by k.o) as columns,
         array(select a.attname from unnest(con.confkey) with ordinality k(n, o)
               join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.n order by k.o) as ref_columns,
         exists (select 1 from pg_index i where i.indrelid = con.conrelid and i.indisunique
                 and (i.indkey::int2[])::int[] @> con.conkey::int[] and array_length(i.indkey::int2[], 1) = array_length(con.conkey, 1)) as one_to_one
  from pg_constraint con
  join pg_class rel on rel.oid = con.conrelid
  join pg_namespace n on n.oid = rel.relnamespace
  join pg_class frel on frel.oid = con.confrelid
  join pg_namespace fn on fn.oid = frel.relnamespace
  where con.contype = 'f' and n.nspname = 'public' and fn.nspname = 'public'
),
enums as (
  select t.typname, array_agg(e.enumlabel order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname
),
funcs as (
  select p.proname, p.proretset,
         rt.typname as ret_type, rtn.nspname as ret_schema, rt.typtype as ret_typtype,
         (select json_agg(json_build_object(
             'name', coalesce(p.proargnames[i], ''),
             'mode', coalesce(p.proargmodes[i], 'i'),
             'type', format_type(coalesce(p.proallargtypes[i], p.proargtypes[i - 1]), null),
             'typname', t.typname, 'elem', et.typname)
           order by i)
          from generate_series(1, coalesce(array_length(p.proallargtypes, 1), p.pronargs)) i
          join pg_type t on t.oid = coalesce(p.proallargtypes[i], p.proargtypes[i - 1])
          left join pg_type et on et.oid = t.typelem and t.typcategory = 'A') as args,
         p.pronargdefaults
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  join pg_type rt on rt.oid = p.prorettype
  join pg_namespace rtn on rtn.oid = rt.typnamespace
  where n.nspname = 'public' and p.prokind = 'f'
    and has_function_privilege('authenticated', p.oid, 'execute')
)
select json_build_object(
  'columns', (select json_agg(cols order by table_name, ordinal_position) from cols),
  'fks', (select coalesce(json_agg(fks order by table_name, conname), '[]') from fks),
  'enums', (select coalesce(json_agg(enums order by typname), '[]') from enums),
  'funcs', (select coalesce(json_agg(funcs order by proname), '[]') from funcs)
)`;

const raw = execFileSync('psql', ['-X', '-A', '-t', '-q', url, '-c', query], { encoding: 'utf8' });
const meta = JSON.parse(raw);
const enumNames = new Set(meta.enums.map((e) => e.typname));

function tsType(udt, dataType) {
  if (dataType === 'ARRAY' || udt.startsWith('_')) return `${tsType(udt.replace(/^_/, ''), '')}[]`;
  if (enumNames.has(udt)) return `Database['public']['Enums']['${udt}']`;
  switch (udt) {
    case 'int2':
    case 'int4':
    case 'int8':
    case 'float4':
    case 'float8':
    case 'numeric':
      return 'number';
    case 'bool':
      return 'boolean';
    case 'json':
    case 'jsonb':
      return 'Json';
    case 'void':
      return 'undefined';
    default:
      return 'string';
  }
}

const tables = new Map();
for (const c of meta.columns) {
  if (!tables.has(c.table_name)) tables.set(c.table_name, []);
  tables.get(c.table_name).push(c);
}

const ind = (n) => '  '.repeat(n);
const out = [];
out.push('// Generated by scripts/gen-db-types.mjs — do not edit by hand. Run `npm run db:types`.');
out.push('');
out.push(
  'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];',
);
out.push('');
out.push('export type Database = {');
out.push(`${ind(1)}__InternalSupabase: { PostgrestVersion: '12' };`);
out.push(`${ind(1)}public: {`);
out.push(`${ind(2)}Tables: {`);
for (const [name, columns] of tables) {
  const row = columns.map(
    (c) =>
      `${ind(5)}${c.column_name}: ${tsType(c.udt_name, c.data_type)}${c.nullable ? ' | null' : ''};`,
  );
  const ins = columns.map(
    (c) =>
      `${ind(5)}${c.column_name}${c.nullable || c.has_default ? '?' : ''}: ${tsType(c.udt_name, c.data_type)}${c.nullable ? ' | null' : ''};`,
  );
  const upd = columns.map(
    (c) =>
      `${ind(5)}${c.column_name}?: ${tsType(c.udt_name, c.data_type)}${c.nullable ? ' | null' : ''};`,
  );
  const rels = meta.fks
    .filter((f) => f.table_name === name)
    .map(
      (f) =>
        `${ind(5)}{\n${ind(6)}foreignKeyName: '${f.conname}';\n${ind(6)}columns: [${f.columns.map((x) => `'${x}'`).join(', ')}];\n${ind(6)}isOneToOne: ${f.one_to_one};\n${ind(6)}referencedRelation: '${f.ref_table}';\n${ind(6)}referencedColumns: [${f.ref_columns.map((x) => `'${x}'`).join(', ')}];\n${ind(5)}},`,
    );
  out.push(`${ind(3)}${name}: {`);
  out.push(`${ind(4)}Row: {`, ...row, `${ind(4)}};`);
  out.push(`${ind(4)}Insert: {`, ...ins, `${ind(4)}};`);
  out.push(`${ind(4)}Update: {`, ...upd, `${ind(4)}};`);
  out.push(`${ind(4)}Relationships: [`, ...rels, `${ind(4)}];`);
  out.push(`${ind(3)}};`);
}
out.push(`${ind(2)}};`);
out.push(`${ind(2)}Views: { [_ in never]: never };`);
out.push(`${ind(2)}Functions: {`);
for (const f of meta.funcs) {
  const args = (f.args ?? []).filter((a) => a.mode === 'i' || a.mode === 'b');
  const outCols = (f.args ?? []).filter((a) => a.mode === 't' || a.mode === 'o');
  const nDefaults = f.pronargdefaults ?? 0;
  const argLines = args.map((a, i) => {
    const optional = i >= args.length - nDefaults;
    const t = a.elem ? `${tsType(a.elem, '')}[]` : tsType(a.typname, '');
    return `${ind(5)}${a.name}${optional ? '?' : ''}: ${t};`;
  });
  out.push(`${ind(3)}${f.proname}: {`);
  out.push(
    argLines.length
      ? `${ind(4)}Args: {\n${argLines.join('\n')}\n${ind(4)}};`
      : `${ind(4)}Args: never;`,
  );
  let returns;
  let setof = null;
  if (outCols.length) {
    returns = `{\n${outCols.map((c) => `${ind(5)}${c.name}: ${tsType(c.typname, '')};`).join('\n')}\n${ind(4)}}[]`;
  } else if (f.ret_typtype === 'c' && tables.has(f.ret_type)) {
    returns = `Database['public']['Tables']['${f.ret_type}']['Row']${f.proretset ? '[]' : ''}`;
    setof = `{ from: '*'; to: '${f.ret_type}'; isOneToOne: ${!f.proretset}; isSetofReturn: ${f.proretset} }`;
  } else {
    returns = tsType(f.ret_type, '') + (f.proretset ? '[]' : '');
  }
  out.push(`${ind(4)}Returns: ${returns};`);
  if (setof) out.push(`${ind(4)}SetofOptions: ${setof};`);
  out.push(`${ind(3)}};`);
}
out.push(`${ind(2)}};`);
out.push(`${ind(2)}Enums: {`);
for (const e of meta.enums)
  out.push(`${ind(3)}${e.typname}: ${e.labels.map((l) => `'${l}'`).join(' | ')};`);
out.push(`${ind(2)}};`);
out.push(`${ind(2)}CompositeTypes: { [_ in never]: never };`);
out.push(`${ind(1)}};`);
out.push('};');
out.push('');
out.push("type PublicSchema = Database['public'];");
out.push(
  "export type Tables<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Row'];",
);
out.push(
  "export type TablesInsert<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Insert'];",
);
out.push(
  "export type TablesUpdate<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Update'];",
);
out.push("export type Enums<T extends keyof PublicSchema['Enums']> = PublicSchema['Enums'][T];");
out.push(
  "export type Functions<T extends keyof PublicSchema['Functions']> = PublicSchema['Functions'][T];",
);
out.push('');

const target = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'lib',
  'database.types.ts',
);
writeFileSync(target, out.join('\n'));
console.log(`Wrote ${target}`);
